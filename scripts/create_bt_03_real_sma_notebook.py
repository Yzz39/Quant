            "- 信号：`close > SMA(window)` 视为趋势偏强\n",
            "- 防未来函数：信号使用 `shift(1)`，即今天收盘确认信号，下一交易日才持仓\n",
            "- 成本：每次仓位变化扣 `0.1%`，粗略代表手续费 + 滑点\n",
