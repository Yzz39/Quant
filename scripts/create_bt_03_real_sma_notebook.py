            "\n",
            "# Set a Chinese-capable font so ETF names render correctly in plot titles.\n",
            "font_candidates = ['Microsoft YaHei', 'SimHei', 'Noto Sans CJK SC', 'Source Han Sans SC', 'Arial Unicode MS']\n",
